/**
 * Icons matching a search, best first: an exact name, then a name that
 * contains the words, then a meaning that does ("gender" -> VenusAndMars).
 */
export function searchIcons(query, names = ICON_NAMES) {
  const q = String(query || "")
    .toLowerCase()
    .trim();
  if (!q) return names;
  const words = q.split(/\s+/).filter(Boolean);
  const scored = [];
  names.forEach((n) => {
    const name = n.toLowerCase();
    const kw = ICON_KEYWORDS[n] || "";
    let score = 0;
    if (name === q.replace(/\s+/g, "")) score = 100;
    else if (words.every((w) => name.includes(w))) score = 60;
    else if (words.every((w) => kw.includes(w) || name.includes(w))) score = 40 + (kw.startsWith(words[0]) ? 5 : 0);
    if (score) scored.push([score, n]);
  });
  return scored.sort((a, b) => b[0] - a[0] || a[1].localeCompare(b[1])).map(([, n]) => n);
}

/** Render an icon by name; unknown names degrade to nothing (never crash). */
export default function Icon({ name, size = 16, color, strokeWidth = 2, className, style }) {
  const Cmp = ICONS[name];
  if (!Cmp) return null;
  return <Cmp size={size} color={color} strokeWidth={strokeWidth} className={className} style={style} aria-hidden="true" />;
}
